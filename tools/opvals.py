#!/usr/bin/env python3
"""Write operating-point node voltages and branch currents as LaTeX macros for D2/D3 figures.

  uv run tools/opvals.py design/amp_tran.asc [-o report/generated/opvals.tex] [--list]

In CircuiTikZ figures (after \\input{generated/opvals.tex}):
  \\opV{vop}      -> 0.900\\,V   node voltage (LTspice node name, lower case)
  \\opI{mn_in_p}  -> 52.1\\,uA    MOSFET drain current |Id| (device name, lower case)
  \\opI{rz_p}     -> current through any other element present in the .op raw
Unknown names render as a bold red ??name so they are impossible to miss on the page.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lt  # noqa: E402
from metrics import Raw  # noqa: E402

HEADER = r"""% generated by tools/opvals.py; do not edit by hand
\providecommand{\opV}[1]{\ifcsname opv@#1\endcsname\csname opv@#1\endcsname\else\textcolor{red}{\textbf{??\detokenize{#1}}}\fi}
\providecommand{\opI}[1]{\ifcsname opi@#1\endcsname\csname opi@#1\endcsname\else\textcolor{red}{\textbf{??\detokenize{#1}}}\fi}
"""


def fmt_i(a: float) -> str:
    a = abs(a)
    if a >= 1e-3:
        return f"{a*1e3:.3g}\\,mA"
    if a >= 1e-6:
        return f"{a*1e6:.3g}\\,$\\mu$A"
    return f"{a*1e9:.3g}\\,nA"


def collect(path: Path) -> tuple[dict[str, float], dict[str, float]]:
    r = lt.run(path, op=True)
    if not r["ok"]:
        raise SystemExit(f".op run failed: {r['errors']}")
    op_raw = Path(r["net"]).with_suffix(".raw")
    volts, amps = {}, {}
    if op_raw.exists():
        raw = Raw(op_raw)
        for low, name in raw.names.items():
            v = float(abs(raw[name][0])) if low.startswith("i") else float(raw[name][0].real)
            if low.startswith("v(") and "," not in low:
                volts[low[2:-1]] = float(raw[name][0].real)
            elif low.startswith(("i(", "ix(")):
                amps[low.split("(", 1)[1].rstrip(")")] = v
    for n, d in (r.get("devices") or {}).items():
        if "Id" in d:
            amps[n.lower()] = abs(d["Id"])
    return volts, amps


def write_opvals(path: Path, out: Path) -> Path:
    volts, amps = collect(Path(path))
    lines = [HEADER]
    for n, v in sorted(volts.items()):
        lines.append(f"\\expandafter\\def\\csname opv@{n}\\endcsname{{{v:.3f}\\,V}}")
    for n, a in sorted(amps.items()):
        lines.append(f"\\expandafter\\def\\csname opi@{n}\\endcsname{{{fmt_i(a)}}}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("file")
    ap.add_argument("-o", "--out", default=str(lt.REPO / "report" / "generated" / "opvals.tex"))
    ap.add_argument("--list", action="store_true", help="print the values instead of only writing the file")
    a = ap.parse_args(argv)
    if a.list:
        volts, amps = collect(Path(a.file))
        for n, v in sorted(volts.items()):
            print(f"V({n}) = {v:.4f} V")
        for n, i in sorted(amps.items()):
            print(f"I({n}) = {i*1e6:.3f} uA")
        return 0
    print(write_opvals(Path(a.file), Path(a.out)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
